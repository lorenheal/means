the x is 10.
the y is 3.
 # single-statement then
if the x greater than the y then
	print "big".
#big
 # single-statement then/else
if the y greater than the x then
	print "y wins".
else
	print "x wins".
#x wins
 # DO/DONE block
if the x greater than 1 then
	DO
		print "block".
		print "still in block".
	DONE.
#block
#still in block
 # nested if
if the x greater than 5 then
	if the x greater than 8 then
		print "very big".
	else
		print "big".
#very big
 # else branch taken
if the y greater than 100 then
	print "nope".
else
	print "yes".
